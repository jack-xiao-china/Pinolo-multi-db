func generateDML(path string) {
	var b strings.Builder
	b.WriteString("-- MySQL 全数据类型测试数据\n")
	b.WriteString("-- 自动生成的DML，覆盖边界值、NULL、空值、特殊字符\n")
	b.WriteString("-- Generated by tools/gen_test_data.go\n\n")
	b.WriteString("SET NAMES utf8mb4;\n")
	b.WriteString("SET FOREIGN_KEY_CHECKS = 0;\n\n")

	genIntTypes(&b)
	genFloatTypes(&b)
	genStringTypes(&b)
	genTextTypes(&b)
	genBinaryTypes(&b)
	genDatetimeTypes(&b)
	genEnumSet(&b)
	genJsonSpatial(&b)
	genIndexTypes(&b)
	genMixed(&b)

	b.WriteString("\nSET FOREIGN_KEY_CHECKS = 1;\n")

	if err := os.WriteFile(path, []byte(b.String()), 0644); err != nil {
		panic(err)
	}
	fmt.Printf("DML written to %s\n", path)
}

