func randString(n int, charsets []string) string {
	all := strings.Join(charsets, "")
	result := make([]byte, n)
	for i := 0; i < n; i++ {
		result[i] = all[r.Intn(len(all))]
	}
	return string(result)
}

func randHex(n int) string {
	const hex = "0123456789ABCDEF"
	result := make([]byte, n*2)
	for i := 0; i < n*2; i++ {
		result[i] = hex[r.Intn(16)]
	}
	return string(result)
}
