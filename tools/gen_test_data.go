// MySQL 全数据类型测试数据生成器
// 生成覆盖所有数据类型、索引类型、边界值、NULL值、特殊字符的DDL和DML

import (
	"fmt"
	"math"
	"math/rand"
	"os"
	"strings"
	"time"
)

var r *rand.Rand

func init() {
	r = rand.New(rand.NewSource(time.Now().UnixNano()))
}

// 特殊字符集
var specialChars = []string{
	"!", "@", "#", "$", "%", "^", "&", "*", "(", ")",
	"~", "`", "_", "+", "=", "{", "}", "[", "]", "|",
	"\\", ":", ";", "\"", "'", "<", ">", ",", ".", "?", "/",
	"中文", "日本語", "한국어", "émoji: 🎉🔥",
	"\t", "\n", "\r",
}

func randSpecialStr() string {
	n := r.Intn(5) + 1
	parts := make([]string, n)
	for i := 0; i < n; i++ {
		parts[i] = specialChars[r.Intn(len(specialChars))]
	}
	return strings.Join(parts, "")
}

func sqlEscape(s string) string {
	s = strings.ReplaceAll(s, "\\", "\\\\")
	s = strings.ReplaceAll(s, "'", "\\'")
	s = strings.ReplaceAll(s, "\n", "\\n")
	s = strings.ReplaceAll(s, "\r", "\\r")
	s = strings.ReplaceAll(s, "\t", "\\t")
	return s
}

